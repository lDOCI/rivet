#!/usr/bin/env python3
"""Write ui/generated/forms.slint from the prototype's list pages.

    tools/gen-forms.py          write the file
    tools/gen-forms.py --check  fail if the file is out of date (CI)

Each page named in ui/spec/forms.toml is read from docs/ux/style/<Page>.dc.html
(its `ROWS`). Order, kinds, titles, captions, ranges, steps and number formats come
from there and nowhere else. The spec names each row; the name becomes the row's
properties (`speed-num`, `light-on`, `now-value`, ...) that app.slint binds to live
data, and the key its callbacks carry (`set-value("speed", 110)`).

A row in the spec is either a name, or a table:
    { name = "now", data = ["value"] }        caption/value/title/range come from live data
    { name = "camera", later = "M4: camera" }  hidden until that function exists
    { name = "spools", repeat = true }         a live list: this row of the prototype is an
                                               example item; the app supplies `spools-items`
    { name = "spools", example = true }        more example items of that list: skipped
A row of the page without an entry is an error: nothing is dropped silently.

Titles are Russian in the prototype; the English msgid comes from i18n/ru (reverse
lookup) or from the page's `en` table in the spec.
"""
import json, pathlib, re, sys, tomllib

ROOT = pathlib.Path(__file__).resolve().parent.parent
STYLE = ROOT / "docs/ux/style"
SPEC = ROOT / "ui/spec/forms.toml"
OUT = ROOT / "ui/generated/forms.slint"
PO = ROOT / "i18n/ru/LC_MESSAGES/rivet.po"

ROW_KINDS = {"section", "link", "info", "toggle", "stepper", "fine", "seg", "action", "slider"}
DATA = {"title", "sub", "value", "range", "tone"}


def proto_page(page):
    src = (STYLE / f"{page}.dc.html").read_text(encoding="utf-8")
    m = re.search(r"var ROWS = (\[.*?\n\]);", src, re.S)
    if not m:
        sys.exit(f"{page}: no ROWS in the prototype page; it is not a list page")
    h1 = re.search(r"<h1[^>]*>([^<]+)</h1>", src).group(1).strip()
    intro = re.search(r"</h1></div>\s*<p[^>]*>([^<]+)</p>", src)
    return json.loads(m.group(1)), h1, intro.group(1).strip() if intro else ""


def po_reverse():
    po = PO.read_text(encoding="utf-8")
    rev = {}
    for mid, mstr in re.findall(r'msgid "((?:[^"\\]|\\.)*)"\nmsgstr "((?:[^"\\]|\\.)*)"', po):
        if mstr and mstr not in rev:
            rev[mstr] = mid
    return rev


def s(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def num(v):
    v = float(v)
    return str(int(v)) if v.is_integer() else repr(v)


def leading_number(text):
    # "5 мм" -> 5, "PLA 50°" -> 50
    m = re.search(r"(-?\d+(?:[.,]\d+)?)", text)
    return float(m.group(1).replace(",", ".")) if m else None


def main():
    check = "--check" in sys.argv
    spec = tomllib.loads(SPEC.read_text(encoding="utf-8"))
    rev = po_reverse()
    missing_tr, errors = [], []

    def tr(page, ru):
        # Numbers, axis letters, "PA": nothing to translate.
        if not re.search(r"[А-Яа-яЁё]", ru):
            return s(ru)
        # A unit keeps its leading space outside the msgid (" мм" -> " " + @tr("mm")).
        if ru != ru.lstrip():
            return f'" " + {tr(page, ru.lstrip())}'
        en = spec[page].get("en", {}).get(ru) or rev.get(ru)
        if not en:
            missing_tr.append(f"{page}: {ru}")
            return s(ru)
        return f"@tr({s(en)})"

    out = [
        "// GENERATED by tools/gen-forms.py from docs/ux/style/*.dc.html and ui/spec/forms.toml.",
        "// Do not edit: change the prototype or the spec and run the tool.",
        'import { FormScreen, FormRow } from "../kit/form.slint";',
        'import { Format } from "../kit/format.slint";',
        "",
    ]
    for page, conf in spec.items():
        rows, h1, intro = proto_page(page)
        entries = {}
        for rid, e in conf.get("rows", {}).items():
            entries[rid] = {"name": e} if isinstance(e, str) else dict(e)
            bad = set(entries[rid].get("data", [])) - DATA
            if bad:
                errors.append(f"{page}: {rid}: unknown data {sorted(bad)}")
        ids = [r["id"] for r in rows if "id" in r]
        for rid in ids:
            if rid not in entries:
                t = next(r.get("t", "") for r in rows if r.get("id") == rid)
                errors.append(f"{page}: row {rid} «{t}» has no entry in ui/spec/forms.toml")
        for rid in entries:
            if rid not in ids:
                errors.append(f"{page}: spec names {rid}, the prototype page has no such row")

        props, bars, items = [], [], []
        # Rows in segments: fixed rows (array literals) and live lists (a property).
        segments = []
        steps, edits = [], []
        for r in rows:
            kind = r.get("kind")
            if kind not in ROW_KINDS:
                errors.append(f"{page}: row kind {kind!r} is not supported by FormScreen")
                continue
            e = entries.get(r.get("id"))
            if not e:
                continue
            n, data, later = e["name"], set(e.get("data", [])), e.get("later")
            # Another example item of a live list: the list row above stands for it.
            if e.get("example"):
                continue
            if e.get("repeat"):
                segments.append("[\n        " + ",\n        ".join(items) + "\n    ]")
                items = []
                props.append(f"    // {r.get('t', '')}: a live list of {kind} rows" + (f" — later: {later}" if later else ""))
                props.append(f"    in property <[FormRow]> {n}-items;")
                segments.append(f"root.{n}-items" if not later else "[]")
                continue
            props.append(f"    // {r.get('t', '')}" + (f" — later: {later}" if later else ""))
            props.append(f"    in property <bool> {n}-shown: {'false' if later else 'true'};")
            if "title" in data:
                props.append(f"    in property <string> {n}-title;")
                title = f"root.{n}-title"
            else:
                title = tr(page, r["t"]) if r.get("t") else '""'

            if kind == "slider":
                props.append(f"    in property <float> {n}-value: {num(r['min'])};")
                props.append(f"    in property <float> {n}-source: -1;")
                big = r.get("bstep") or max(r["step"], (r["max"] - r["min"]) / 10)
                bars.append(
                    f'{{ key: "{n}", title: {title}, value: root.{n}-value, source: root.{n}-source, '
                    f"min: {num(r['min'])}, max: {num(r['max'])}, step: {num(r['step'])}, big-step: {num(big)}, "
                    f"unit: {s(r.get('unit', ''))}, off-at-zero: {'true' if r.get('fmt') == 'off0' else 'false'}, "
                    f"shown: root.{n}-shown }}")
                continue

            if "sub" in data:
                props.append(f"    in property <string> {n}-sub;")
            else:
                sub = tr(page, r["sub"]) if r.get("sub") else '""'
                props.append(f"    in property <string> {n}-sub: {sub};")
            f = [f'kind: "{kind}"', f'key: "{n}"', f"title: {title}", f"sub: root.{n}-sub",
                 f"shown: root.{n}-shown"]
            if kind in ("link", "info"):
                # The prototype's values are examples: the app always supplies them.
                props.append(f"    in property <string> {n}-value;")
                f.append(f"value: root.{n}-value")
            if "tone" in data:
                props.append(f"    in property <string> {n}-tone;")
                f.append(f"tone: root.{n}-tone")
            elif r.get("tone"):
                f.append(f"tone: {s(r['tone'])}")
            if kind == "action":
                props.append(f"    in property <bool> {n}-enabled: true;")
                f.append(f"on: root.{n}-enabled")
            if kind == "toggle":
                props.append(f"    in property <bool> {n}-on;")
                f.append(f"on: root.{n}-on")
            if kind == "seg":
                props.append(f"    in property <int> {n}-sel: {int(r.get('v', 0))};")
                f.append("opts: [" + ", ".join(tr(page, o) for o in r["opts"]) + "]")
                f.append(f"sel: root.{n}-sel")
                values = [leading_number(o) for o in r["opts"]]
                if all(v is not None for v in values):
                    props.append(f"    // The options as numbers, for the app.")
                    props.append(f"    out property <[float]> {n}-values: [{', '.join(num(v) for v in values)}];")
            if kind in ("stepper", "fine"):
                dec, unit = int(r.get("dec", 0)), r.get("unit", "")
                lo, hi = r["min"], r["max"]
                if "range" in data:
                    props.append(f"    in property <float> {n}-min: {num(lo)};")
                    props.append(f"    in property <float> {n}-max: {num(hi)};")
                    lo_e, hi_e = f"root.{n}-min", f"root.{n}-max"
                else:
                    lo_e, hi_e = num(lo), num(hi)
                props.append(f"    in property <float> {n}-num: {num(max(lo, min(hi, 0)) if kind == 'stepper' else r.get('def', lo))};")
                label = f"Format.fixed(root.{n}-num, {dec}) + {tr(page, unit) if unit.strip() else s(unit)}"
                f.append(f"value: {label}")
                if kind == "stepper":
                    f.append(f"big: {num(r['step'])}")
                else:
                    props.append(f"    in property <float> {n}-was-num: {num(r.get('def', 0))};")
                    scale = 10 ** dec
                    f += [f"big: {num(r['steps'][0])}", f"small: {num(r['steps'][1])}",
                          f"big-label: {s(num(r['steps'][0]))}", f"small-label: {s(num(r['steps'][1]))}",
                          f"changed: round(root.{n}-num * {scale}) != round(root.{n}-was-num * {scale})",
                          f"was: Format.fixed(root.{n}-was-num, {dec}) + {tr(page, unit) if unit.strip() else s(unit)}"]
                scale = 10 ** dec
                steps.append(f'        if (key == "{n}") {{ root.set-value(key, max({lo_e}, min({hi_e}, round((root.{n}-num + d) * {scale}) / {scale}))); }}')
                kt = r["t"] + (", " + unit.strip() if unit.strip() else "")
                edits.append(f'        if (key == "{n}") {{ root.edit-number(key, {tr(page, kt)}, {lo_e}, {hi_e}, root.{n}-num, {dec}); }}')
            if kind == "link" and r.get("ic"):
                f.append(f"icon: {s(' '.join(r['ic']))}")
            items.append("{ " + ", ".join(f) + " }")

        out.append(f"// {page}.dc.html")
        out.append(f"export component {conf['component']} inherits FormScreen {{")
        out += props
        if conf.get("title") == "data":
            out.append("    in property <string> page-title;")
            out.append("    title: root.page-title;")
        else:
            out.append(f"    title: {tr(page, h1)};")
        if intro:
            out.append(f"    intro: {tr(page, intro)};")
        if conf.get("back") is False:
            out.append("    has-back: false;")
        out.append("    // A stepper's new value, clamped to its range and rounded to its decimals.")
        out.append("    callback set-value(string, float);")
        out.append("    // Type a stepper's value: key, title, min, max, current, decimals.")
        out.append("    callback edit-number(string, string, float, float, float, int);")
        out.append("    stepped(key, d) => {")
        out += steps
        out.append("    }")
        out.append("    edit(key) => {")
        out += edits
        out.append("    }")
        out.append("    bars: [" + ",\n        ".join(bars) + "];")
        segments.append("[\n        " + ",\n        ".join(items) + "\n    ]")
        if len(segments) > 5:
            errors.append(f"{page}: more than 5 row segments; FormScreen shows 5")
        for k, seg in enumerate(segments[:5]):
            out.append(f"    {'rows' if k == 0 else f'rows-{k}'}: {seg};")
        out.append("}")
        out.append("")
    if missing_tr:
        errors.append("no English msgid (add to i18n or the page's `en` table):\n  " + "\n  ".join(missing_tr))
    if errors:
        sys.exit("\n".join(errors))
    text = "\n".join(out)
    if check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            sys.exit(f"{OUT.relative_to(ROOT)} is out of date: run tools/gen-forms.py")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(spec)} pages")


if __name__ == "__main__":
    main()
