#!/usr/bin/env python3
"""Write ui/generated/forms.slint from the prototype's list pages.

    tools/gen-forms.py          write the file
    tools/gen-forms.py --check  fail if the file is out of date (CI)

Each page named in ui/spec/forms.toml is read from docs/ux/style/<Page>.dc.html
(its `ROWS`). Order, kinds, titles, captions, ranges and steps come from there and
nowhere else. The spec only names each row (`r0 = "light"`): that name becomes the
row's properties (`light-on`, `light-shown`, ...) that app.slint binds to live data.
A row of the page without a name in the spec is an error: nothing is dropped silently.

Titles are Russian in the prototype; the English msgid comes from i18n/ru (reverse
lookup) or from the page's `en` table in the spec.
"""
import json, pathlib, re, sys, tomllib

ROOT = pathlib.Path(__file__).resolve().parent.parent
STYLE = ROOT / "docs/ux/style"
SPEC = ROOT / "ui/spec/forms.toml"
OUT = ROOT / "ui/generated/forms.slint"
PO = ROOT / "i18n/ru/LC_MESSAGES/rivet.po"

ROW_KINDS = {"section", "link", "info", "toggle", "stepper", "fine", "seg", "action", "slider"}


def proto_rows(page):
    src = (STYLE / f"{page}.dc.html").read_text(encoding="utf-8")
    m = re.search(r"var ROWS = (\[.*?\n\]);", src, re.S)
    if not m:
        sys.exit(f"{page}: no ROWS in the prototype page; it is not a list page")
    return json.loads(m.group(1)), re.search(r"<h1[^>]*>([^<]+)</h1>", src).group(1).strip()


def po_reverse():
    po = PO.read_text(encoding="utf-8")
    rev = {}
    for mid, mstr in re.findall(r'msgid "((?:[^"\\]|\\.)*)"\nmsgstr "((?:[^"\\]|\\.)*)"', po):
        if mstr and mstr not in rev:
            rev[mstr] = mid
    return rev


def slint_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def num(v):
    return repr(float(v)) if not float(v).is_integer() else str(int(v))


def main():
    check = "--check" in sys.argv
    spec = tomllib.loads(SPEC.read_text(encoding="utf-8"))
    rev = po_reverse()
    missing_tr, errors = [], []

    def tr(page, ru):
        en = spec[page].get("en", {}).get(ru) or rev.get(ru)
        if not en:
            missing_tr.append(f"{page}: {ru}")
            return slint_str(ru)
        return f"@tr({slint_str(en)})"

    out = [
        "// GENERATED by tools/gen-forms.py from docs/ux/style/*.dc.html and ui/spec/forms.toml.",
        "// Do not edit: change the prototype or the spec and run the tool.",
        'import { FormScreen } from "../kit/form.slint";',
        "",
    ]
    for page, conf in spec.items():
        rows, h1 = proto_rows(page)
        names = conf.get("rows", {})
        ids = [r["id"] for r in rows if "id" in r]
        for rid in ids:
            if rid not in names:
                t = next(r.get("t", "") for r in rows if r.get("id") == rid)
                errors.append(f"{page}: row {rid} «{t}» has no name in ui/spec/forms.toml")
        for rid in names:
            if rid not in ids:
                errors.append(f"{page}: spec names {rid}, the prototype page has no such row")
        props, bars, items = [], [], []
        for r in rows:
            kind = r.get("kind")
            if kind not in ROW_KINDS:
                errors.append(f"{page}: row kind {kind!r} is not supported by FormScreen")
                continue
            key = names.get(r.get("id"), "")
            if not key:
                continue
            title = tr(page, r["t"]) if r.get("t") else '""'
            props.append(f"    in property <bool> {key}-shown: true;")
            if kind == "slider":
                props.append(f"    in property <float> {key}-value: {num(r['min'])};")
                props.append(f"    in property <float> {key}-source: -1;")
                big = r.get("bstep") or max(r["step"], (r["max"] - r["min"]) / 10)
                bars.append(
                    f'{{ key: "{key}", title: {title}, value: root.{key}-value, source: root.{key}-source, '
                    f"min: {num(r['min'])}, max: {num(r['max'])}, step: {num(r['step'])}, big-step: {num(big)}, "
                    f"unit: {slint_str(r.get('unit', ''))}, off-at-zero: {'true' if r.get('fmt') == 'off0' else 'false'}, "
                    f"shown: root.{key}-shown }}")
                continue
            sub = tr(page, r["sub"]) if r.get("sub") else '""'
            props.append(f"    in property <string> {key}-sub: {sub};")
            f = [f'kind: "{kind}"', f'key: "{key}"', f"title: {title}", f"sub: root.{key}-sub",
                 f"shown: root.{key}-shown"]
            if kind in ("link", "info", "stepper", "fine"):
                props.append(f"    in property <string> {key}-value;")
                f.append(f"value: root.{key}-value")
            if kind in ("info", "action") and r.get("tone"):
                f.append(f"tone: {slint_str(r['tone'])}")
            if kind == "toggle":
                props.append(f"    in property <bool> {key}-on;")
                f.append(f"on: root.{key}-on")
            if kind == "seg":
                props.append(f"    in property <int> {key}-sel;")
                f.append("opts: [" + ", ".join(tr(page, o) for o in r["opts"]) + "]")
                f.append(f"sel: root.{key}-sel")
            if kind == "stepper":
                f.append(f"big: {num(r['step'])}")
            if kind == "fine":
                props.append(f"    in property <bool> {key}-changed;")
                props.append(f"    in property <string> {key}-was;")
                f += [f"big: {num(r['steps'][0])}", f"small: {num(r['steps'][1])}",
                      f"changed: root.{key}-changed", f"was: root.{key}-was"]
            if kind == "link" and r.get("ic"):
                f.append(f"icon: {slint_str(' '.join(r['ic']))}")
            items.append("{ " + ", ".join(f) + " }")
        out.append(f"// {page}.dc.html")
        out.append(f"export component {conf['component']} inherits FormScreen {{")
        out += props
        out.append(f"    title: {tr(page, h1)};")
        out.append("    bars: [" + ",\n        ".join(bars) + "];")
        out.append("    rows: [\n        " + ",\n        ".join(items) + "\n    ];")
        out.append("}")
        out.append("")
    if missing_tr:
        errors.append("no English msgid (add to i18n or the page's `en` table):\n  " + "\n  ".join(missing_tr))
    if errors:
        sys.exit("\n".join(errors))
    text = "\n".join(out)
    if check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            sys.exit(f"{OUT.relative_to(ROOT)} is out of date: run tools/gen-forms.py")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(spec)} pages")


if __name__ == "__main__":
    main()
