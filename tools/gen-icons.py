#!/usr/bin/env python3
"""Write ui/kit/icons.slint from the icon set used by the prototype (docs/ux/style/gen.py).

One source of truth: the prototype and the app draw the same 24x24 stroke paths.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'docs', 'ux', 'style'))
import gen  # noqa: E402

out = ['// Generated by tools/gen-icons.py from docs/ux/style/gen.py. Do not edit.',
       '// 24x24 viewbox, stroke icons: draw with kit Icon.', '',
       'export global Icons {']
import re  # noqa: E402

NUM = r'-?(?:\d+\.?\d*|\.\d+)'


def absolute_start(path):
    # Each prototype path is its own <path>, where a leading relative 'm' is
    # absolute. Joined into one command string it would be relative to the
    # previous subpath, so rewrite 'm x y rest' as 'M x y l rest'.
    m = re.match(r'\s*m\s*(%s)[\s,]*(%s)(.*)$' % (NUM, NUM), path, re.S)
    if not m:
        return path
    x, y, rest = m.groups()
    rest = rest.strip()
    if rest and not rest[0].isalpha():
        rest = 'l' + rest
    return 'M%s %s%s' % (x, y, (' ' + rest) if rest else '')


for name, paths in sorted(gen.ICONS.items()):
    d = ' '.join(absolute_start(p) for p in paths if p).replace('"', '')
    out.append('    out property <string> %s: "%s";' % (name.replace('_', '-'), d))
out.append('}')
with open(os.path.join(ROOT, 'ui', 'kit', 'icons.slint'), 'w') as f:
    f.write('\n'.join(out) + '\n')
print('icons:', len(gen.ICONS))
